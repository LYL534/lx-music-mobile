// 生成 ios/LxMusicMobile/UserApi/UserApiPreload.generated.swift:
// 将 Android assets 的 user-api-preload.js 以 base64 分块字符串嵌入 Swift,
// iOS 的 UserApiScriptExecutor(JSContext) 运行时解码后使用, 与 Android QuickJS 共享同一份 preload。
// 用 base64 而不是直接内嵌 JS 文本: base64 字母表不含引号/反斜杠/换行,
// 对 git 的 LF/CRLF 换行转换完全免疫(曾因 CRLF 导致 Swift 续行反斜杠失效, 构建失败)。
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const src = path.join(root, 'android/app/src/main/assets/script/user-api-preload.js')
const out = path.join(root, 'ios/LxMusicMobile/UserApi/UserApiPreload.generated.swift')

if (!fs.existsSync(src)) {
  console.error('[generate-ios-preload] missing:', src)
  process.exit(1)
}

const js = fs.readFileSync(src, 'utf8')
const b64 = Buffer.from(js, 'utf8').toString('base64')
// 按 76 字符分块, 每块一行纯字符串(仅 [A-Za-z0-9+/=], 无任何转义风险)
const chunks = b64.match(/.{1,76}/g) ?? []
const chunkLines = chunks.map(c => `        "${c}",`).join('\n')

const swift = `// Generated by scripts/generate-ios-preload.js — DO NOT EDIT
// Source: android/app/src/main/assets/script/user-api-preload.js
// 与 Android QuickJS 共享的同一份 preload 脚本, 以 base64 嵌入(运行时解码)。

import Foundation

enum UserApiPreload {
    static let script: String = {
        let base64 = [
${chunkLines}
        ].joined()
        return String(data: Data(base64Encoded: base64) ?? Data(), encoding: .utf8) ?? ""
    }()
}
`

fs.writeFileSync(out, swift)
console.log('[generate-ios-preload] generated:', out)
