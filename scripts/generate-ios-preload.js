// 生成 ios/LxMusicMobile/UserApi/UserApiPreload.generated.swift:
// 将 Android assets 的 user-api-preload.js 以字符串常量形式嵌入 Swift,
// iOS 的 UserApiScriptExecutor(JSContext) 直接使用, 与 Android QuickJS 共享同一份 preload。
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const src = path.join(root, 'android/app/src/main/assets/script/user-api-preload.js')
const out = path.join(root, 'ios/LxMusicMobile/UserApi/UserApiPreload.generated.swift')

if (!fs.existsSync(src)) {
  console.error('[generate-ios-preload] missing:', src)
  process.exit(1)
}

const js = fs.readFileSync(src, 'utf8')
// Swift 字符串字面量转义: 反斜杠、双引号、换行(美元符号${不受影响, Swift 插值只认 \( )
const escaped = js
  .replace(/\\/g, '\\\\')
  .replace(/"/g, '\\"')
  .replace(/\n/g, '\\n\\\n')

const swift = `// Generated by scripts/generate-ios-preload.js — DO NOT EDIT
// Source: android/app/src/main/assets/script/user-api-preload.js
// 与 Android QuickJS 共享的同一份 preload 脚本(iOS 端由 JSContext 加载)。

import Foundation

enum UserApiPreload {
    static let script = "${escaped}"
}
`

fs.writeFileSync(out, swift)
console.log('[generate-ios-preload] generated:', out)
